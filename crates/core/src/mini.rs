    /// Слова-маркеры жаргона: в формулировках для владельца бизнеса их быть не должно.
    /// Короткие (h1, alt, lcp…) ищем как отдельные слова, чтобы не цеплять обычные слова.
    fn jargon(text: &str) -> Option<&'static str> {
        const SUBSTR: &[&str] = &["canonical", "sitemap", "json-ld", "schema", "ttfb", "robots.txt", "noindex", "hreflang", "og:", "http/2", "http/3"];
        const WORDS: &[&str] = &["lcp", "cls", "inp", "h1", "alt", "cdn", "waf", "tls", "hsts", "cms"];
        let low = text.to_lowercase();
        if let Some(m) = SUBSTR.iter().find(|m| low.contains(**m)) {
            return Some(m);
        }
        let tokens: Vec<&str> = low.split(|c: char| !c.is_alphanumeric()).collect();
        WORDS.iter().find(|w| tokens.contains(w)).copied()
    }

