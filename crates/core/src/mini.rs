    /// Пункт 9: тексты, которые берутся из пояснения, не несут адресов, имён файлов и кодов ответа.
    #[test]
    fn client_text_from_detail_has_no_technical_leaks() {
        let cases = [
            r("B04", Status::Fail, "HTTPS не работает: сертификат выдан на другой домен (x.example.org) — браузер покажет ошибку"),
            r("B04", Status::Fail, "Сертификат не проходит проверку: tls handshake eof"),
            r("B05", Status::Fail, "Перенаправления на https нет, а сам HTTPS не работает").with_value("no_redirect"),
            r("F13", Status::Fail, "© 2019 — сайт давно не обновлялся").with_value(2019),
            r("I01", Status::Fail, "Googlebot закрыт в robots.txt").with_value("robots"),
            r("I02", Status::Fail, "Закрыты поисковые ИИ-боты: OAI-SearchBot").with_value("OAI-SearchBot"),
            r("I05", Status::Warn, "защита отказала: OAI-SearchBot (403)"),
        ];
        for c in &cases {
            for lang in ["ru", "en"] {
                let t = plain_text_lang(c, lang);
                for bad in ["example", "robots.txt", "403", "404", ".css", "Googlebot", "OAI-SearchBot", "GPTBot", "handshake", ".txt"] {
                    assert!(!t.contains(bad), "{}/{lang}: «{t}» содержит «{bad}»", c.id);
                }
            }
        }
    }

