/// Сервисы по списку ботов из значения или пояснения результата.
fn services_in(r: &MetricResult, table: &[(&'static str, &'static str, &'static str)], en: bool) -> Vec<&'static str> {
    let text = r.value.as_ref().and_then(|v| v.as_str()).map(str::to_string).unwrap_or_else(|| r.detail.clone());
    let mut out: Vec<&'static str> = Vec::new();
    for (bot, ru, en_name) in table {
        let name = if en { en_name } else { ru };
        // `ClaudeBot` — подстрока `Claude-SearchBot`? Нет, но `GPTBot` — не подстрока `OAI-SearchBot`: разделение по токенам надёжнее.
        let hit = text.split(|c: char| !(c.is_alphanumeric() || c == '-')).any(|t| t.eq_ignore_ascii_case(bot));
        if hit && !out.contains(name) {
            out.push(name);
        }
    }
    out
}

/// Сервисы, поиск которых настройки сайта реально закрывают: по значению результата I02
/// (только поисковые боты и боты по запросу пользователя), у старых результатов — по пояснению.
/// `yandex` — закрыт ещё и Яндекс (I03): добавляются Алиса и Нейро.
pub fn ai_blocked_services(i02: Option<&MetricResult>, yandex: bool, en: bool) -> Vec<&'static str> {
    let mut out = i02.map(|r| services_in(r, AI_SEARCH_SERVICES, en)).unwrap_or_default();
    if yandex {
        if en {
            out.push("Yandex AI answers");
        } else {
            out.extend(["Алиса", "Нейро"]);
        }
    }
    out
}

/// Сервисы, чьи боты обучения закрыты (I04).
pub fn ai_trained_services(i04: &MetricResult, en: bool) -> Vec<&'static str> {
    services_in(i04, AI_TRAIN_SERVICES, en)
}

/// Кабинеты вебмастера, подтверждённые по метатегам из пояснения C21, в падеже «в …».
fn webmaster_names(detail: &str, en: bool) -> Vec<&'static str> {
    let mut out = Vec::new();
    if detail.contains("yandex-verification") {
        out.push(if en { "Yandex Webmaster" } else { "Яндекс Вебмастере" });
    }
    if detail.contains("google-site-verification") {
        out.push("Google Search Console");
    }
    if detail.contains("msvalidate.01") {
        out.push("Bing Webmaster Tools");
    }
    out
}

/// «В порядке» по факту результата — там, где общая формулировка метрики сказала бы больше измеренного.
fn ok_by_fact(r: &MetricResult, lang: &str) -> Option<String> {
    let en = lang == "en";
    match r.id.as_str() {
        "C21" => {
            let names = webmaster_names(&r.detail, en);
            if names.is_empty() {
                None
            } else if en {
                Some(format!("The site is verified in {}", join_list(&names, true)))
            } else {
                Some(format!("Сайт подтверждён в {}", join_list(&names, false)))
            }
        }
        _ => None,
    }
}

